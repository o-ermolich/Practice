package by.lessons.task_12;

public class Character {
    private String name;
    private String surname;

    public Character() {
    }

    public String getName() {
        return name;
    }

    public String getSurname() {
        return surname;
    }

    public Character (String name, String surname) {
        this.name = name;
        this.surname = surname;
    }
}
